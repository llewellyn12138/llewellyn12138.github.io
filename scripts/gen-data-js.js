#!/usr/bin/env node
'use strict';
/*
 * Generate <script>-loadable data snapshots next to the JSON files.
 *
 * Why: fetch() of a local .json is blocked by CORS under file://, so pages
 * opened by double-click cannot load manifests / latest posts. A plain
 * <script src="...js"> IS allowed under file://. The JS reads global data
 * as a fallback; over HTTP it still prefers a live fetch() of the .json.
 *
 * Run: node scripts/gen-data-js.js
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');

const SECTIONS = ['games', 'tools', 'software'];

for (const name of SECTIONS) {
  const jsonPath = path.join(root, name, 'manifest.json');
  if (!fs.existsSync(jsonPath)) {
    console.warn('[data-js] skip (missing) ' + name + '/manifest.json');
    continue;
  }
  const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const out = path.join(root, name, 'manifest.js');
  fs.writeFileSync(
    out,
    '/* Generated by scripts/gen-data-js.js — do not edit by hand.\n' +
      '   Source of truth: manifest.json */\n' +
      'window.PF_MANIFEST = window.PF_MANIFEST || {};\n' +
      'window.PF_MANIFEST[' + JSON.stringify(name) + '] = ' +
      JSON.stringify(data, null, 2) + ';\n',
    'utf8'
  );
  console.log('[data-js] wrote ' + name + '/manifest.js');
}

// Latest posts: use dist/blog-latest.json when available, else fall back to
// an existing root snapshot. This is a PREVIEW snapshot for file:// usage;
// over HTTP the widget fetches the live /blog-latest.json instead.
const candidates = [
  path.join(root, 'dist', 'blog-latest.json'),
  path.join(root, 'blog-latest.json'),
];
let latest = null;
for (const p of candidates) {
  if (fs.existsSync(p)) {
    try { latest = JSON.parse(fs.readFileSync(p, 'utf8')); break; }
    catch (e) { /* ignore malformed */ }
  }
}
const out = path.join(root, 'blog-latest.js');
if (latest) {
  fs.writeFileSync(
    out,
    '/* Generated by scripts/gen-data-js.js — preview snapshot for file://.\n' +
      '   Over HTTP the widget fetches blog-latest.json (always fresh). */\n' +
      'window.PF_LATEST_POSTS = ' + JSON.stringify(latest.posts || [], null, 2) + ';\n',
    'utf8'
  );
  console.log('[data-js] wrote blog-latest.js (' + (latest.posts || []).length + ' posts)');
} else {
  fs.writeFileSync(out, 'window.PF_LATEST_POSTS = [];\n', 'utf8');
  console.log('[data-js] wrote empty blog-latest.js (run build-site.js first for posts)');
}
